import { Role } from '@prisma/client';

/**
 * Покупатель и staff — разные учётки, даже если Telegram один.
 *
 * У ботов свои колонки: `User.telegramId` — адрес покупателя в основном боте (и
 * якорь входа в мобилку), `User.staffTelegramId` — адрес кабинета в боте продавца.
 * Поэтому один человек спокойно совмещает роли: в основном боте он покупает, в
 * боте продавца ведёт магазин, и это две независимые строки User.
 *
 * Раньше колонка была одна, и совмещение было запрещено в обе стороны — иначе
 * получалось молчаливое слияние личностей: заказы и телефон покупателя ложились
 * в учётку продавца. С разделением ботов запрет снят и не нужен.
 *
 * Единственный оставшийся инвариант: один Telegram = максимум один покупатель и
 * максимум один staff-аккаунт (обе колонки unique).
 */
export const isStaffRole = (role: Role): boolean =>
  role === Role.SELLER || role === Role.SUPER_ADMIN;

